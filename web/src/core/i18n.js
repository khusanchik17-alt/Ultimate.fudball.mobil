const DICTS = { en, uz, ru };

export class I18n {
  constructor(language = 'uz') {
    this.language = DICTS[language] ? language : 'uz';
    this.listeners = new Set();
  }

  setLanguage(code) {
    if (!DICTS[code] || code === this.language) return;
    this.language = code;
    for (const fn of this.listeners) fn(code);
  }

  onChange(fn) {
    this.listeners.add(fn);
    return () => this.listeners.delete(fn);
  }

  /** translate with {placeholder} interpolation */
  t(key, vars) {
    const dict = DICTS[this.language] || en;
    let str = dict[key];
    if (str === undefined) str = en[key];
    if (str === undefined) str = key;
    if (vars) {
      str = str.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
    }
    return str;
  }
}

export const i18n = new I18n();
export const t = (key, vars) => i18n.t(key, vars);
export const POS_LABEL = (pos) => i18n.t(`pos.${pos}`);
